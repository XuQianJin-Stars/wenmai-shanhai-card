/** 第一章随时可考；其后要先通关对应故事章——和文物志同一把钥匙。 */
export function quizStageOpen(S, save, chapters) {
  const C = chapters.find((x) => x.key === S.ch);
  if (!C) return false;
  if (C.n === 1) return true;
  return save.isDone(C.levels.at(-1).id);
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** 从题库抽 n 道，选项顺序打乱。 */
export function dealQuiz(bank, n = QUIZ_N) {
  return shuffle(bank).slice(0, n).map((q) => {
    const opts = shuffle([q.ok, ...q.no]);
    return { ask: q.ask, opts, ans: opts.indexOf(q.ok), note: q.note };
  });
}

export function todayKey() {
  const t = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${t.getFullYear()}-${p(t.getMonth() + 1)}-${p(t.getDate())}`;
}
